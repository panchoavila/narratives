import { describe, it, expect } from 'vitest';
import { buildSourceExport, localizeUrlImports, exportSlug, isBuilderMetadataPath } from './source-export';

const PAGE = "'use client';\nexport default function Page() { return <div data-id=\"root\" />; }\n";
const NOW = new Date('2026-09-30T12:00:00Z');

describe('buildSourceExport (standalone Next.js export)', () => {
  it('omits draft content from runnable exports without deleting it from the authoring project', async () => {
    const input = { 'cms/posts.json': '[{"_id":"a","_status":"published"},{"_id":"b","_status":"draft","title":"Unpublished title"}]' };
    const opts = { name: 'Public', runtimeRange: '^1', now: NOW };
    expect((await buildSourceExport(input, opts)).files['cms/posts.json']).not.toContain('Unpublished title');
    expect((await buildSourceExport(input, { ...opts, cmsContent: 'all' })).files['cms/posts.json']).toBe(input['cms/posts.json']);
    expect(input['cms/posts.json']).toContain('Unpublished title');
  });
  it('excludes secret and hidden input paths while preserving authoring data and root ignore rules', async () => {
    const input = { 'app/page.tsx': PAGE, '.env': 'secret', '.env.local': 'secret', '.env.example': 'not a safe generated template', 'lib/.env.production': 'secret', '.git/config': 'secret', '_meta/session.json': 'private', '.gitignore': 'node_modules\n' };
    const out = await buildSourceExport(input, { name: 'Safe', runtimeRange: '^1' });
    for (const file of ['.env', '.env.local', '.env.example', 'lib/.env.production', '.git/config', '_meta/session.json']) expect(out.files[file]).toBeUndefined();
    expect(out.files['.gitignore']).toBe('node_modules\n');
    expect(input['.env.local']).toBe('secret');
  });
  it('ships the project minus builder metadata, plus the Next.js scaffold', async () => {
    const out = await buildSourceExport({
      'app/page.client.tsx': PAGE,
      'app/page.tsx': "import P from './page.client';\nexport default function Page() { return <P />; }\n",
      '_meta/agent-chats.json': '{}',
      '_revyme/variants/t/a.tsx': PAGE,
      'cms/posts.json': '[]',
    }, { name: 'Halden Studio', runtimeRange: '^0.0.28', now: NOW, fetchImpl: async () => { throw new Error('no network'); } });
    expect(Object.keys(out.files).sort()).toEqual([
      '.gitignore', 'README.md', 'app/page.client.tsx', 'app/page.tsx', 'cms/posts.json', 'next.config.mjs', 'package.json', 'tsconfig.json',
    ]);
    expect(out.filename).toBe('halden-studio.zip');
    const pkg = JSON.parse(out.files['package.json']);
    expect(pkg).toMatchObject({ name: 'halden-studio', private: true, scripts: { dev: 'next dev', build: 'next build' } });
    expect(pkg.dependencies['@revyme/runtime']).toBe('^0.0.28');
    expect(pkg.dependencies.next).toBe('^16');
    expect(pkg.dependencies).not.toHaveProperty('gsap');
    expect(JSON.parse(out.files['tsconfig.json']).compilerOptions.paths).toEqual({ '@/*': ['./*'] });
    // Next 16: no removed `next lint` script, no unsupported `eslint` config key.
    expect(pkg.scripts).not.toHaveProperty('lint');
    expect(out.files['next.config.mjs']).not.toContain('eslint');
    expect(out.files['README.md']).toMatch(/^# Halden Studio\n/);
  });

  it('exports builder forms as a portable route from the current editable configuration', async () => {
    const form = `<form data-id="f1" data-form='{"sendTo":[{"type":"sheet","sheetId":"sheet","sheetName":"Leads"}]}'><input name="Email" /></form>`;
    const original = '// AUTO-GENERATED by Revyme — same-origin relay to the Forms Worker. Do not edit.\nimport { env } from "cloudflare:workers";';
    const opts = { name: 'Forms', runtimeRange: '^1', now: NOW };
    const first = await buildSourceExport({ 'app/page.client.tsx': form, 'app/api/form/route.ts': original }, opts);
    expect(first.files['app/api/form/route.ts']).toBeUndefined();
    expect(first.files['app/api/form/route.js']).toContain("runtime = 'nodejs'");
    expect(JSON.parse(first.files['app/api/form/forms.json']).f1).toMatchObject({ allowedFields: ['Email'] });
    expect(first.files['README.md']).toContain('GOOGLE_SERVICE_ACCOUNT_EMAIL');
    const updated = await buildSourceExport({ ...first.files, 'app/page.client.tsx': form.replace('Leads', 'Updated') }, opts);
    expect(JSON.parse(updated.files['app/api/form/forms.json']).f1.sendTo[0].sheetName).toBe('Updated');
    const custom = await buildSourceExport({ 'app/page.client.tsx': form, 'app/api/form/route.ts': 'export function POST() {}' }, opts);
    expect(custom.files['app/api/form/route.ts']).toBe('export function POST() {}');
    expect(custom.files['app/api/form/route.js']).toBeUndefined();
  });

  it('keeps the existing Forms Worker relay for webhook destinations', async () => {
    const form = `<form data-id="f1" data-form='{"sendTo":[{"type":"webhook","url":"https://example.test/hook"}]}' />`;
    const relay = '// AUTO-GENERATED by Revyme — same-origin relay to the Forms Worker. Do not edit.\nimport { env } from "cloudflare:workers";';
    const opts = { name: 'Forms', runtimeRange: '^1', now: NOW };
    const out = await buildSourceExport({ 'app/page.client.tsx': form, 'app/api/form/route.ts': relay }, opts);
    expect(out.files['app/api/form/route.ts']).toBe(relay);
    expect(out.files['app/api/form/route.js']).toBeUndefined();
    const previousPortable = { 'app/page.client.tsx': form, 'app/api/form/route.js': '// AUTO-GENERATED by Revyme — portable form route', 'app/api/form/handler.mjs': 'old', 'app/api/form/forms.json': '{}' };
    const migrated = await buildSourceExport(previousPortable, opts);
    expect(migrated.files['app/api/form/route.ts']).toContain('cloudflare:workers');
    expect(migrated.files['app/api/form/route.js']).toBeUndefined();
    expect(migrated.files['app/api/form/handler.mjs']).toBeUndefined();
  });

  it('keeps the project\'s own config files; README is always added', async () => {
    const out = await buildSourceExport({
      'app/page.client.tsx': PAGE,
      'package.json': '{"name":"mine"}',
      'next.config.js': 'module.exports = {};',
      'tsconfig.json': '{}',
      '.gitignore': 'x',
    }, { name: null, runtimeRange: '^1', now: NOW });
    expect(out.files['package.json']).toBe('{"name":"mine"}');
    expect(out.files['next.config.mjs']).toBeUndefined();
    expect(out.files['tsconfig.json']).toBe('{}');
    expect(out.files['.gitignore']).toBe('x');
    expect(out.files['README.md']).toMatch(/^# Narratives project/);
    expect(out.filename).toBe('revyme-site.zip');
  });

  it('preserves a TypeScript Next config and the library files it imports without generating a conflicting config', async () => {
    const config = "import { redirects } from './lib/redirects';\nexport default { redirects };\n";
    const redirects = "export async function redirects() { return [{ source: '/old', destination: '/new', permanent: true }]; }\n";
    const schema = "export const schema = { '@type': 'Organization' };\n";
    const page = "import { schema } from '@/lib/schema';\nexport default function Page() { return JSON.stringify(schema); }\n";
    const out = await buildSourceExport({ 'next.config.ts': config, 'lib/redirects.ts': redirects, 'lib/schema.ts': schema, 'app/page.tsx': page }, { name: 'REAL', runtimeRange: '^1', now: NOW });
    expect(out.files['next.config.ts']).toBe(config);
    expect(out.files['next.config.mjs']).toBeUndefined();
    expect(out.files['lib/redirects.ts']).toBe(redirects);
    expect(out.files['lib/schema.ts']).toBe(schema);
    expect(out.files['app/page.tsx']).toBe(page);
  });

  it('downloads marketplace components imported by URL and rewrites the imports (nested, deduped)', async () => {
    const A = 'https://assets.revyme.app/components/ArcMeter@0123456789abcdef.js';
    const B = 'https://assets.revyme.app/components/Dial@fedcba9876543210.js';
    const fetched: string[] = [];
    const out = await localizeUrlImports({
      'app/page.client.tsx': `import ArcMeter from "${A}";\nimport Again from '${A}';`,
      'styles.css': `/* ${A} */`,
    }, async (url) => {
      fetched.push(url);
      return url === A ? `import Dial from "${B}"; export default 1;` : 'export default 2;';
    });
    expect(fetched).toEqual([A, B]);
    expect(out.files['app/page.client.tsx']).toBe('import ArcMeter from "@/components/remote/ArcMeter-01234567.js";\nimport Again from \'@/components/remote/ArcMeter-01234567.js\';');
    expect(out.files['components/remote/ArcMeter-01234567.js']).toBe('import Dial from "@/components/remote/Dial-fedcba98.js"; export default 1;');
    expect(out.files['components/remote/Dial-fedcba98.js']).toBe('export default 2;');
    expect(out.files['styles.css']).toBe(`/* ${A} */`);   // not a module
    expect(out.downloaded).toEqual(['components/remote/Dial-fedcba98.js', 'components/remote/ArcMeter-01234567.js']);
  });

  it('an unreachable bundle stays a URL and is reported', async () => {
    const A = 'https://assets.revyme.app/components/ArcMeter@0123456789abcdef.js';
    const out = await localizeUrlImports({ 'app/page.client.tsx': `import X from "${A}";` }, async () => { throw new Error('offline'); });
    expect(out.files['app/page.client.tsx']).toBe(`import X from "${A}";`);
    expect(out.failed).toEqual([A]);
  });

  it('slugs and metadata paths', () => {
    expect(exportSlug('  My Site!! ')).toBe('my-site');
    expect(exportSlug('')).toBe('revyme-site');
    expect(isBuilderMetadataPath('_meta/x.json')).toBe(true);
    expect(isBuilderMetadataPath('app/_private/page.tsx')).toBe(false);
  });
});
